import os, pathlib, tempfile
HERE = os.path.dirname(os.path.abspath(__file__)); os.chdir(HERE)
APP = pathlib.Path(HERE).parent.joinpath('inkling.html').as_uri()
import asyncio, json
from playwright.async_api import async_playwright
async def main():
    async with async_playwright() as p:
        b = await p.chromium.launch(); pg = await b.new_page(viewport={'width':1440,'height':900})
        errs=[]; pg.on('pageerror', lambda e: errs.append(str(e)))
        await pg.add_init_script(open('mock3d.js').read() + "\ndocument.addEventListener('contextmenu', e => { window.__ctx = e.defaultPrevented; });")
        await pg.goto(APP); await pg.wait_for_timeout(900)
        await pg.click('#newNotebook'); await pg.fill('.modal input.field', 'K'); await pg.keyboard.press('Enter'); await pg.wait_for_timeout(300)
        await (await pg.query_selector_all('.kind'))[2].click(); await pg.click('.modal .btn.primary'); await pg.wait_for_timeout(600)
        for (x,y,t) in [(400,300,'A'),(700,320,'B'),(500,600,'C')]:
            await pg.mouse.dblclick(x,y); await pg.keyboard.type(t); await pg.keyboard.press('Escape'); await pg.wait_for_timeout(120); await pg.mouse.click(1000, 750)
        await pg.click('#dock [data-tool="pen"]'); await pg.mouse.move(450,420); await pg.mouse.down(); await pg.mouse.move(650,440, steps=6); await pg.mouse.up()
        await pg.click('#dock [data-tool="select"]')
        notes = lambda: pg.evaluate("[...document.querySelectorAll('.obj-note')].map(n=>[n.innerText.trim(), Math.round(n.getBoundingClientRect().x), Math.round(n.getBoundingClientRect().y)])")
        # right-drag around A, B and the drawing
        await pg.mouse.move(300, 240); await pg.mouse.down(button="right"); await pg.mouse.move(1000, 470, steps=8); await pg.mouse.up(button='right'); await pg.wait_for_timeout(200)
        print('right-drag selected:', await pg.evaluate("(document.querySelector('#objbar .rlabel')||{}).innerText"), '| native menu blocked:', await pg.evaluate('window.__ctx'))
        await pg.click('#objbar button[aria-label^="Group them"]'); await pg.click('.menu button:has-text("circle")'); await pg.wait_for_timeout(200)
        print('group circle exists:', await pg.evaluate("!!document.querySelector('.obj-group.circle')"))
        await pg.mouse.click(1000, 750); await pg.wait_for_timeout(100)
        before = await notes()
        a = [n for n in await pg.query_selector_all('.obj-note') if (await n.inner_text()).strip()=='A'][0]; ab = await a.bounding_box()
        await pg.mouse.move(ab['x']+20, ab['y']+10); await pg.mouse.down(); await pg.mouse.move(ab['x']+80, ab['y']+70, steps=6); await pg.mouse.up(); await pg.wait_for_timeout(200)
        after = await notes(); print('drag A moves group:', before, '->', after)
        await pg.mouse.click(1000, 750)
        await pg.keyboard.down('Alt'); await pg.mouse.click(ab['x']+80, ab['y']+70); await pg.keyboard.up('Alt'); await pg.wait_for_timeout(100)
        print('alt-click selects one:', await pg.evaluate("(document.querySelector('#objbar .rlabel')||{innerText:'single'}).innerText"))
        await pg.mouse.click(1000, 750)
        await pg.mouse.click(ab['x']+80, ab['y']+70, button='right'); await pg.wait_for_timeout(200)
        items = await pg.evaluate("[...document.querySelectorAll('.menu button,.menu .mlabel')].map(b=>b.innerText)")
        print('right-click menu:', items)
        await pg.click('.menu button:has-text("Lock")'); await pg.wait_for_timeout(200)
        b2 = await notes()
        await pg.mouse.move(ab['x']+90, ab['y']+80); await pg.mouse.down(); await pg.mouse.move(ab['x']+190, ab['y']+180, steps=6); await pg.mouse.up(); await pg.wait_for_timeout(200)
        print('locked drag blocked:', b2 == await notes(), '|', await pg.inner_text('#toast'))
        await pg.keyboard.press('Delete'); await pg.wait_for_timeout(200)
        print('locked delete blocked:', len(await notes()) == 3, '| lock badge:', await pg.evaluate("!!document.querySelector('.lockbadge')"))
        await pg.mouse.click(ab['x']+90, ab['y']+80, button='right'); await pg.wait_for_timeout(150)
        await pg.click('.menu button:has-text("Unlock")'); await pg.wait_for_timeout(150)
        await pg.mouse.click(ab['x']+90, ab['y']+80, button='right'); await pg.wait_for_timeout(150)
        await pg.click('.menu button:has-text("Ungroup")'); await pg.wait_for_timeout(200)
        print('ungrouped:', not await pg.evaluate("!!document.querySelector('.obj-group')"))
        z0 = await pg.inner_text('#zoomLabel')
        await pg.click('#dock [data-tool="hand"]'); await pg.mouse.move(700, 500); await pg.mouse.wheel(0, -300); await pg.wait_for_timeout(150)
        print('hand tool scroll zoom:', z0, '->', await pg.inner_text('#zoomLabel'))
        await pg.screenshot(path='t10.png')
        print('ERRORS', errs)
        await b.close()
asyncio.run(main())
